#!/usr/bin/env python3
"""Generate jm01 schedule.json from live sources and optionally publish it.

Typical uses:
  python generate.py --fixture fixtures/ppa_events.html --dry-run   # offline test
  python generate.py --dry-run                                      # live, no write
  python generate.py --publish                                      # live, commit+push

Zero third-party dependencies for the schedule path (stdlib only).
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import ppa  # noqa: E402
import validate as validate_mod  # noqa: E402

try:
    import seeds as seeds_mod  # noqa: E402
except Exception:  # pragma: no cover - seeds module is optional
    seeds_mod = None


def load_json(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def content_key(doc: dict) -> str:
    """Hash of the meaningful content only (ignores 'updated' / 'note')."""
    sub = {"events": doc.get("events"), "seeds": doc.get("seeds")}
    return hashlib.sha256(
        json.dumps(sub, sort_keys=True, ensure_ascii=False).encode("utf-8")
    ).hexdigest()


def carry_seeds(new_seeds, old, events, today):
    """Keep the last good seeds until their event has ended, so one failed
    scrape doesn't blank the Top Seeds face."""
    if new_seeds:
        return new_seeds
    old_seeds = (old or {}).get("seeds")
    if not old_seeds:
        return None
    for e in events:
        if e["name"] == old_seeds.get("event"):
            try:
                if datetime.date.fromisoformat(e["end"]) >= today:
                    return old_seeds
            except ValueError:
                pass
    return None


def run_git(cmd, cwd, env=None):
    print("+ git", " ".join(cmd))
    subprocess.run(["git", *cmd], cwd=cwd, env=env, check=True)


def publish(repo_root, out_path, cfg):
    env = os.environ.copy()
    # Prefer an env var (set by the Pi's systemd unit) so the Pi never has to
    # edit tracked config.json — a local edit there would block the rebase below.
    key = os.environ.get("JM01_DEPLOY_KEY") or cfg.get("deploy_key")
    if key:
        env["GIT_SSH_COMMAND"] = (
            f"ssh -i {key} -o IdentitiesOnly=yes -o StrictHostKeyChecking=accept-new"
        )
    branch = cfg.get("branch", "main")
    # Commit the already-written schedule.json first, THEN rebase onto the remote
    # and push. Pulling before committing fails on the unstaged schedule.json.
    run_git(["add", os.path.relpath(out_path, repo_root)], repo_root)
    if subprocess.run(["git", "diff", "--cached", "--quiet"], cwd=repo_root).returncode == 0:
        print("Nothing staged — schedule file unchanged.")
        return
    run_git(["commit", "-m", "schedule: update from scraper"], repo_root)
    run_git(["pull", "--rebase", "origin", branch], repo_root, env)
    run_git(["push", "origin", branch], repo_root, env)
    print("Pushed schedule.json. The device picks it up within an hour.")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=os.path.join(HERE, "config.json"))
    ap.add_argument("--out", help="schedule.json path (default: repo root)")
    ap.add_argument("--fixture", help="parse a saved HTML file instead of fetching live")
    ap.add_argument("--no-seeds", action="store_true", help="skip the seeds scrape")
    ap.add_argument("--publish", action="store_true", help="git commit & push if changed")
    ap.add_argument("--dry-run", action="store_true", help="print, don't write or push")
    args = ap.parse_args()

    cfg = load_json(args.config) or {}
    repo_root = cfg.get("repo_root") or os.path.dirname(HERE)
    out_path = args.out or os.path.join(repo_root, "schedule.json")
    overrides = cfg.get("name_overrides", {})
    today = datetime.date.today()

    if args.fixture:
        with open(args.fixture, encoding="utf-8", errors="replace") as f:
            html = f.read()
    else:
        html = ppa.fetch_html()

    events = ppa.parse_events(html, overrides=overrides)
    clean = [{k: v for k, v in e.items() if not k.startswith("_")} for e in events]

    old = load_json(out_path)

    new_seeds = None
    seeds_cfg = cfg.get("seeds", {})
    if not args.no_seeds and seeds_mod and seeds_cfg.get("enabled"):
        try:
            new_seeds = seeds_mod.fetch_seeds(events, cfg, today)
        except Exception as ex:  # seeds are best-effort; never fail the schedule
            print(f"[seeds] skipped: {ex}", file=sys.stderr)
    seeds = carry_seeds(new_seeds, old, clean, today)

    doc = {
        "note": "Generated by scraper/generate.py - do not edit by hand.",
        "updated": today.isoformat(),
        "events": clean,
    }
    if seeds:
        doc["seeds"] = seeds

    validate_mod.validate(doc, old, today, min_upcoming=cfg.get("min_upcoming", 1))

    if old and content_key(old) == content_key(doc):
        print(f"No change: {len(clean)} events, seeds={'yes' if seeds else 'no'}.")
        return 0

    print(json.dumps(doc, indent=2, ensure_ascii=False))
    if args.dry_run:
        print("\n(dry run - nothing written)")
        return 0

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"\nWrote {out_path}: {len(clean)} events, seeds={'yes' if seeds else 'no'}.")

    if args.publish:
        publish(repo_root, out_path, cfg)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
